local t = require("t")
local B = require("build")
local detect = require("model.detect")

local function fresh(over, mode)
  local tr = B.tracker("u-a", B.cfg(mode or "nuzlocke", over))
  tr:start()
  tr:place("route-101")
  return tr
end

t.case("first snapshot with several mons is baseline", function()
  local tr = B.tracker("u-a", B.cfg())
  local facts = tr:start()
  t.eq(#facts, 0)
  t.ok(tr.st.started)
  t.eq(tr.st.baseline["0000b001"], true)
  t.eq(tr.st.mons, {})
  -- baseline mons are ignored forever, even when they faint or evolve
  tr.recs[0xB001].hp = 0
  tr.recs[0xB002].species = 5
  t.eq(#tr:step(), 0)
end)

t.case("first snapshot with exactly one mon is the starter", function()
  local tr = B.tracker("u-a", B.cfg("soullink"))
  local facts = tr:start({ 0x1234 })
  local c = B.fact(facts, "catch")
  t.eq(c.route, "starter")
  t.eq(c.starter, true)
  t.eq(c.counts, true)
  t.eq(tr.st.routes.starter.mon, "00001234")
  t.eq(tr.st.routes.starter.kind, "starter")
  t.eq(tr.st.order, { "00001234" })
end)

t.case("tracking waits for team and boxes", function()
  local st, facts = detect.diff(nil, { team = { B.rec({ p = 1, sp = 3 }) } }, B.cfg(), {})
  t.eq(st.started, false)
  t.eq(#facts, 0)
  st = detect.diff(st, { team = { B.rec({ p = 1, sp = 3 }) }, boxes = {} }, B.cfg(), {})
  t.eq(st.started, true)
  t.eq(st.routes.starter ~= nil, true)
end)

t.case("explicit first = baseline", function()
  local st = detect.diff(nil, { team = { B.rec({ p = 1, sp = 3 }) }, boxes = {} }, B.cfg(), { first = "baseline" })
  t.eq(st.baseline["00000001"], true)
  t.eq(next(st.routes), nil)
end)

t.case("catch on the current place", function()
  local tr = fresh()
  local facts = tr:catch(0x100, 10, { nick = "Blob", lv = 3 })
  local c = B.fact(facts, "catch")
  t.eq(c.route, "route-101")
  t.eq(c.counts, true)
  t.eq(c.nickname, "Blob")
  local m = tr.st.mons["00000100"]
  t.eq(m.species, 10); t.eq(m.where, "box"); t.eq(m.route, "route-101"); t.eq(m.level, 3)
  t.eq(tr.st.routes["route-101"], { status = "caught", mon = "00000100", species = 10, kind = "wild" })
  t.eq(#tr:step(), 0, "nothing new on the next poll")
end)

t.case("second catch on a used route is extra", function()
  local tr = fresh()
  tr:catch(0x100, 10)
  local c = B.fact(tr:catch(0x101, 11), "catch")
  t.eq(c.counts, false); t.eq(c.why, "extra")
  t.eq(tr.st.mons["00000101"].why, "extra")
  t.eq(tr.st.routes["route-101"].mon, "00000100")
end)

t.case("first_encounter_only off keeps the entry, marks additional", function()
  local tr = fresh({ first_encounter_only = false })
  tr:catch(0x100, 10)
  local c = B.fact(tr:catch(0x101, 11), "catch")
  t.eq(c.why, "additional")
  t.eq(tr.st.routes["route-101"].mon, "00000100")
end)

t.case("dupes clause: same species keeps the route open", function()
  local tr = fresh()
  tr:catch(0x100, 10)
  tr:place("route-102")
  local c = B.fact(tr:catch(0x101, 10), "catch")
  t.eq(c.why, "dupe"); t.eq(c.counts, false)
  t.eq(tr.st.routes["route-102"], nil)
  local c2 = B.fact(tr:catch(0x102, 12), "catch")
  t.eq(c2.counts, true)
  t.eq(tr.st.routes["route-102"].mon, "00000102")
end)

t.case("dupes clause off", function()
  local tr = fresh({ dupes_clause = false })
  tr:catch(0x100, 10)
  tr:place("route-102")
  t.eq(B.fact(tr:catch(0x101, 10), "catch").counts, true)
end)

t.case("family hook is used for dupes", function()
  local tr = B.tracker("u-a", B.cfg(), nil, { family = function(sp) return sp // 10 end })
  tr:start(); tr:place("route-101")
  tr:catch(0x100, 11)
  tr:place("route-102")
  t.eq(B.fact(tr:catch(0x101, 19), "catch").why, "dupe")
end)

t.case("shiny clause: shiny does not consume the route", function()
  local tr = fresh()
  local c = B.fact(tr:catch(0x100, 10, { shiny = true }), "catch")
  t.eq(c.why, "shiny"); t.eq(c.counts, false)
  t.eq(tr.st.routes["route-101"], nil)
  t.eq(B.fact(tr:catch(0x101, 11), "catch").counts, true)
  local tr2 = fresh({ shiny_clause = false })
  t.eq(B.fact(tr2:catch(0x100, 10, { shiny = true }), "catch").counts, true)
end)

t.case("egg is a gift and consumes no route", function()
  local tr = fresh()
  local c = B.fact(tr:catch(0x100, 10, { egg = true }), "catch")
  t.eq(c.gift, true); t.eq(c.counts, false)
  t.eq(tr.st.mons["00000100"].gift, true)
  t.eq(tr.st.routes["route-101"], nil)
  t.eq(B.fact(tr:catch(0x101, 11), "catch").counts, true)
  -- hatching keeps the mon a gift
  tr.recs[0x100].egg = false
  tr:step()
  t.eq(tr.st.mons["00000100"].gift, true)
end)

t.case("evolution keeps the mon and reports it", function()
  local tr = fresh()
  tr:catch(0x100, 10)
  tr.recs[0x100].species = 11
  local facts = tr:step()
  local e = B.fact(facts, "evolve")
  t.eq(e.from, 10); t.eq(e.to, 11)
  t.eq(B.count(facts, "catch"), 0)
  t.eq(tr.st.mons["00000100"].species, 11)
  t.eq(tr.st.routes["route-101"].species, 10)
end)

t.case("death needs a known hp transition from above zero", function()
  local tr = fresh()
  tr:catch(0x100, 10)
  local d = B.fact(tr:hp(0x100, 0), "death")
  t.eq(d.deaths, 1); t.eq(d.route, "route-101")
  t.eq(#tr:step(), 0, "still fainted: no second death")
  tr:hp(0x100, 12)
  t.eq(B.fact(tr:hp(0x100, 0), "death").deaths, 2)
  t.eq(tr.st.mons["00000100"].deaths, 2)
  -- unknown hp never produces a death
  local tr2 = fresh()
  tr2.recs[0x100] = B.rec({ p = 0x100, sp = 10 })
  tr2.box[#tr2.box + 1] = 0x100
  tr2:step()
  tr2.recs[0x100].hp = 0
  t.eq(B.count(tr2:step(), "death"), 0, "no previous hp known")
end)

t.case("no place: catch recorded without route and reported", function()
