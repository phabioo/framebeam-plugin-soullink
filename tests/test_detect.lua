t.case("moves between team and box, gone after two polls", function()
  local tr = fresh()
  tr:catch(0x100, 10)
  tr.box = {}; tr.team = { table.unpack(tr.team) }; tr.team[#tr.team + 1] = 0x100
  local f = B.fact(tr:step(), "moved")
  t.eq(f.to, "team")
  t.eq(tr.st.order, { "00000100" })
  tr.team = { 0xB001, 0xB002 }
  t.eq(B.count(tr:step(), "moved"), 0)
  t.eq(tr.st.mons["00000100"].where, "team")
  t.eq(B.fact(tr:step(), "moved").to, "gone")
  tr.team[#tr.team + 1] = 0x100
  t.eq(B.fact(tr:step(), "moved").to, "team")
end)

t.case("unknown parts never mark mons gone", function()
  local tr = fresh()
  tr:catch(0x100, 10)
  local snap = tr:snapshot()
  snap.boxes = nil
  local st = detect.diff(tr.st, snap, B.cfg(), {})
  st = detect.diff(st, snap, B.cfg(), {})
  st = detect.diff(st, snap, B.cfg(), {})
  t.eq(st.mons["00000100"].where, "box")
  t.eq(st.mons["00000100"].miss, nil)
end)

t.case("diff does not modify the previous state", function()
  local tr = fresh()
  local before = require("model.util").encode(tr.st)
  local snap = tr:snapshot()
  snap.team[#snap.team + 1] = B.rec({ p = 0x777, sp = 20 })
  detect.diff(tr.st, snap, B.cfg(), {})
  t.eq(require("model.util").encode(tr.st), before)
end)

t.case("place from location and zone table", function()
  local zones = { [7] = "route-104", [8] = false }
  local st, facts = detect.diff(nil, { location = { zone = 7, name = "Some Name" } }, B.cfg(), { zones = zones })
  t.eq(st.place.key, "route-104"); t.eq(st.place.name, "Some Name")
  t.eq(B.fact(facts, "place").key, "route-104")
  st, facts = detect.diff(st, { location = { zone = 8, name = "Town" } }, B.cfg(), { zones = zones })
  t.eq(st.place.key, nil); t.eq(st.place.zone, 8)
  st = detect.diff(st, { location = { zone = 99, name = "?" } }, B.cfg(), { zones = zones })
  t.eq(st.place.key, nil)
  -- unknown zone keeps a manual place
  local st2 = detect.set_place(nil, "route-110")
  st2 = detect.diff(st2, { location = { zone = 99 } }, B.cfg(), { zones = zones })
  t.eq(st2.place.key, "route-110"); t.eq(st2.place.manual, true)
end)

t.case("set_place: keys, free text, clear", function()
  local st, f = detect.set_place(nil, "route-104")
  t.eq(st.place, { key = "route-104", manual = true }); t.eq(f.kind, "place")
  st, f = detect.set_place(st, "Secret Cove", "Secret Cove")
  t.eq(st.place.key, "place:Secret Cove")
  st, f = detect.set_place(st, "")
  t.eq(st.place.key, nil)
  local _, none = detect.set_place(st, "")
  t.eq(none, nil)
end)

t.case("battle: encounter then missed", function()
  local tr = fresh()
  local f = B.fact(tr:battle(30), "encounter")
  t.eq(f.counts, true); t.eq(f.route, "route-101"); t.eq(f.species, 30)
  t.eq(tr.st.routes["route-101"].status, "encounter")
  t.eq(B.count(tr:step(), "encounter"), 0, "one fact per battle")
  local m = B.fact(tr:end_battle(), "missed")
  t.eq(m.route, "route-101")
  t.eq(tr.st.routes["route-101"].status, "missed")
  -- a second wild battle on the used route does not count
  local f2 = B.fact(tr:battle(31), "encounter")
  t.eq(f2.counts, false); t.eq(f2.why, "used")
end)

t.case("battle: catch during the battle", function()
  local tr = fresh()
  tr:battle(30)
  local c = B.fact(tr:catch(0x100, 30), "catch")
  t.eq(c.counts, true)
  t.eq(B.count(tr:end_battle(), "missed"), 0)
  t.eq(tr.st.routes["route-101"].status, "caught")
end)

t.case("battle: catch after the battle closed upgrades a missed route of that species", function()
  local tr = fresh()
  tr:battle(30)
  tr:end_battle()
