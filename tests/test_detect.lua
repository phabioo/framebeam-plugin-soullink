t.case("encounters list when battle() is unavailable", function()
  local tr = fresh()
  tr.snap_extra.encounters = { { species = 30 } }
  local f = B.fact(tr:step(), "encounter")
  t.eq(f.counts, true)
  t.eq(tr.st.routes["route-101"].status, "encounter")
  -- trainer battles (wild = false) are ignored
  local tr2 = fresh()
  tr2.snap_extra.battle = { active = true, wild = false, foes = { B.rec({ p = 9, sp = 3 }) } }
  t.eq(B.count(tr2:step(), "encounter"), 0)
end)

t.case("badges accept number, count table or list", function()
  local s = detect.diff(nil, { badges = 3 }, B.cfg(), {})
  t.eq(s.badges, 3)
  s = detect.diff(s, { badges = { count = 5 } }, B.cfg(), {})
  t.eq(s.badges, 5)
