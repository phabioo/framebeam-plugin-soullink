t.case("battle: dupes, shiny, hordes", function()
  local tr = fresh()
  tr:catch(0x100, 30)
  tr:place("route-102")
  tr:end_battle()
  local f = B.fact(tr:battle(30), "encounter")
  t.eq(f.why, "dupe")
  t.eq(tr.st.routes["route-102"], nil)
  tr:end_battle()
  t.eq(B.count(tr.last_facts, "missed"), 0)
  local fs = B.fact(tr:battle(40, { shiny = true }), "encounter")
  t.eq(fs.why, "shiny"); t.eq(fs.counts, false)
  tr:end_battle()
  local fh = B.fact(tr:battle(41, { horde = true }), "encounter")
  t.eq(fh.why, "horde"); t.eq(tr.st.routes["route-102"], nil)
  tr:end_battle()
  local tr2 = fresh({ hordes_count = true })
  t.eq(B.fact(tr2:battle(41, { horde = true }), "encounter").counts, true)
  t.eq(tr2.st.routes["route-101"].kind, "horde")
end)

