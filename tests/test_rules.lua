local t = require("t")
local rules = require("model.rules")
local oras = require("data.oras")
local B = require("build")
local ID = "uzume.soullink"

t.case("defaults", function()
  local d = rules.defaults()
  t.eq(d.first_encounter_only, true)
  t.eq(d.dupes_clause, true)
  t.eq(d.shiny_clause, true)
  t.eq(d.hordes_count, false)
  t.eq(d.pairs_differ_primary_type, false)
  t.eq(d.only_linked_in_team, false)
  t.eq(d.nickname_required, true)
  t.eq(d.level_caps, true)
end)

t.case("mode falls back to participants", function()
  t.eq(rules.parse(nil).mode, "nuzlocke")
  t.eq(rules.parse(B.run({ "Lena" })).mode, "nuzlocke")
  t.eq(rules.parse(B.run({ "Lena", "Jonas" })).mode, "soullink")
  local run = B.run({ "Lena", "Jonas", "Sam" })
  run.participants[2].status = "invited"
  run.participants[3].status = "declined"
  t.eq(rules.parse(run).mode, "nuzlocke")
end)

t.case("explicit mode wins", function()
  local run = B.run({ "Lena", "Jonas" }, { [ID] = { mode = "nuzlocke" } })
  local cfg = rules.parse(run)
  t.eq(cfg.mode, "nuzlocke")
  t.eq(cfg.mode_set, true)
  run = B.run({ "Lena" }, { [ID] = { mode = "soullink" } })
  t.eq(rules.parse(run).mode, "soullink")
end)

t.case("unknown keys ignored, wrong types default", function()
  local run = B.run({ "Lena" }, { [ID] = { mode = "banana", rules = {
    dupes_clause = false, hordes_count = "yes", level_caps = 3, extra = true, shiny_clause = false } }, other = {} })
  local cfg = rules.parse(run)
  t.eq(cfg.mode, "nuzlocke")
  t.eq(cfg.mode_set, false)
  t.eq(cfg.rules.dupes_clause, false)
  t.eq(cfg.rules.shiny_clause, false)
  t.eq(cfg.rules.hordes_count, false)
  t.eq(cfg.rules.level_caps, true)
  t.eq(cfg.rules.extra, nil)
end)

t.case("settings of other shapes", function()
  t.eq(rules.parse({ settings = { [ID] = "x" } }).rules, rules.defaults())
  t.eq(rules.parse({ settings = "x" }).mode, "nuzlocke")
end)

t.case("normalize and to_settings round trip", function()
  local cfg = rules.normalize({ dupes_clause = false })
  t.eq(cfg.mode, "nuzlocke")
  t.eq(cfg.rules.dupes_clause, false)
  local s = rules.to_settings({ mode = "soullink", rules = { hordes_count = true } })
  local again = rules.parse({ settings = s, participants = {} })
  t.eq(again.mode, "soullink")
  t.eq(again.rules.hordes_count, true)
end)

t.case("route keys and labels", function()
  t.eq(oras.route_number("route-120"), 120)
  t.eq(oras.route_number("route-135"), nil)
  t.eq(oras.custom_key("  Cave  of\tx "), "place:Cave of x")
  t.eq(oras.custom_key("   "), nil)
  t.ok(oras.is_key("starter") and oras.is_key("route-101") and oras.is_key("place:Foo") and oras.is_key("loc:301"))
  t.ok(not oras.is_key("route-1") and not oras.is_key("foo") and not oras.is_key("place:") and not oras.is_key("loc:") and not oras.is_key("loc:x"))
  t.eq(oras.area_key(301), "loc:301"); t.eq(oras.area_key(301.0), "loc:301"); t.eq(oras.area_key("x"), nil)
  t.eq(oras.area_id("loc:301"), 301); t.eq(oras.area_id("route-101"), nil)
  t.ok(oras.is_route("loc:5") and oras.is_route("route-101") and not oras.is_route("starter") and not oras.is_route("place:x"))
  local tr = function(k, v) return k .. (v and v.n and (":" .. v.n) or "") end
  t.eq(oras.label("route-104", tr), "route:104")
  t.eq(oras.label("place:My Spot", tr), "My Spot")
  t.eq(oras.label("loc:7", tr), "area:7", "fallback without a name")
  t.eq(oras.label("loc:7", tr, { loc = { ["7"] = "Some Cave" } }), "Some Cave")
  local keys = { "place:b", "loc:9", "route-102", "starter", "loc:3", "route-101", "place:a" }
  table.sort(keys, oras.compare)
  t.eq(keys, { "starter", "route-101", "route-102", "loc:3", "loc:9", "place:a", "place:b" })
  local order = { ["loc:9"] = 1, ["loc:3"] = 2 }
  table.sort(keys, function(a, b) return oras.compare(a, b, order) end)
  t.eq(keys, { "starter", "route-101", "route-102", "loc:9", "loc:3", "place:a", "place:b" }, "game order")
  t.eq(next(oras.ZONE_TO_ROUTE), nil)
  t.eq(oras.ROUTE_KEYS, nil, "no hard-coded route list")
  t.eq(oras.level_cap(0), 15)
  t.eq(oras.level_cap(8), nil)
end)
